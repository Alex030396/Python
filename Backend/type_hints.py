# TYPE HINTS

my_string = "My string variable"
print(my_string)
print(type(my_string))

my_string = 5
print(my_string)
print(type(my_string))

my_type_string: str = "My typed String variable"
print(my_type_string)
print(type(my_type_string))

my_type_string: int = 5
print(my_type_string)
print(type(my_type_string))